#!/usr/bin/env python3
"""Regenerate configs/boards.tsv from a dtbloader checkout.

dtbloader (https://github.com/TravMurav/dtbloader, BSD-3-Clause) is the EFI driver the
aarch64-laptops community uses to pick a device tree from SMBIOS. Its data has two halves:

  scripts/hwids/*.txt   `fwupdtool hwids` dumps: the SMBIOS strings of one real machine,
                        plus the CHID GUID derived from each field combination.
  src/devices/*.c       one `struct device` per DTB, listing the CHID GUIDs it accepts.

Joining them on the "Manufacturer + ProductName" CHID gives exact SMBIOS vendor/product
strings for each DTB, which is what GRUB's `smbios` command can read (it cannot compute
CHIDs). Only Snapdragon X1/X2 laptops are kept.

Usage: import-dtbloader-boards.py DTBLOADER_DIR COMMIT > configs/boards.tsv
"""

import re
import sys
from pathlib import Path

IN_SCOPE = re.compile(r"^(x1e|x1p|hamoa|purwa|glymur|mahua)")

GUID_C = re.compile(
    r"\{\s*0x([0-9a-f]{8}),\s*0x([0-9a-f]{4}),\s*0x([0-9a-f]{4}),\s*\{([^}]*)\}\s*\}", re.I
)


def c_guid(m):
    tail = [b.strip().lower().removeprefix("0x").zfill(2) for b in m.group(4).split(",")]
    return f"{m.group(1)}-{m.group(2)}-{m.group(3)}-{''.join(tail[:2])}-{''.join(tail[2:])}".lower()


def parse_devices(root):
    """Yield (dtb, name, extra_match, tentative, guids) per struct device."""
    for f in sorted((root / "src/devices").glob("*.c")):
        text = f.read_text()
        arrays = {}
        for am in re.finditer(r"EFI_GUID\s+(\w+)\[\]\s*=\s*\{(.*?)\n\};", text, re.S):
            arrays[am.group(1)] = {c_guid(g) for g in GUID_C.finditer(am.group(2))}
        for dm in re.finditer(r"struct device\s+\w+\s*=\s*\{(.*?)\n\};", text, re.S):
            body = dm.group(1)
            dtb = re.search(r'\.dtb\s*=\s*L"qcom\\\\([^"]+)"(.*)', body)
            name = re.search(r'\.name\s*=\s*L"([^"]+)"', body)
            hw = re.search(r"\.hwids\s*=\s*(\w+)", body)
            if not (dtb and name and hw):
                continue
            yield {
                "dtb": dtb.group(1),
                "name": name.group(1),
                "extra_match": ".extra_match" in body,
                "tentative": "tentative" in dtb.group(2).lower(),
                "guids": arrays.get(hw.group(1), set()),
                "src": f.name,
            }


def parse_hwids(f):
    fields, chids = {}, {}
    for line in f.read_text(errors="replace").splitlines():
        m = re.match(r"^(\w+):\s*(.*)$", line)
        if m:
            fields[m.group(1)] = m.group(2).strip()
        m = re.match(r"^\{([0-9a-f-]+)\}\s*<-\s*(.+)$", line.strip())
        if m:
            chids[m.group(2).strip()] = m.group(1).lower()
    return fields, chids


def grub_safe(s):
    return bool(s) and not re.search(r"[\"'$\\\t\n]", s)


def product_regex(vendor, product):
    """ERE for GRUB's `regexp`. Lenovo's ProductName is the machine type plus a SKU suffix
    (ThinkPad "21N10001US", Yoga "83ED"); the first four characters are the machine type and
    are shared by every SKU of that model, so match on that prefix. Others match exactly."""
    if vendor == "LENOVO":
        return "^" + re.escape(product[:4])
    return "^" + re.sub(r"([.\[\]()*+?{}|^$\\])", r"\\\1", product) + "$"


def main():
    root, commit = Path(sys.argv[1]), sys.argv[2]
    devices = [d for d in parse_devices(root) if IN_SCOPE.match(d["dtb"])]
    rows = {}
    for f in sorted((root / "scripts/hwids").glob("*.txt")):
        fields, chids = parse_hwids(f)
        key = chids.get("Manufacturer + ProductName")
        vendor, product = fields.get("Manufacturer", ""), fields.get("ProductName", "")
        if not key or not grub_safe(vendor) or not grub_safe(product):
            continue
        for d in devices:
            if key in d["guids"]:
                rows[(vendor, product_regex(vendor, product), d["dtb"])] = d

    # A vendor/product pair is auto-selected only when exactly one plain candidate claims it.
    # Devices with an .extra_match hook (e.g. ThinkPad T14s OLED vs IPS, told apart by an ACPI
    # memory probe) cannot be distinguished from GRUB, so they stay menu-only.
    plain, ambiguous = {}, set()
    for (v, p, _), d in rows.items():
        if d["extra_match"]:
            ambiguous.add((v, p))
        else:
            plain.setdefault((v, p), set()).add(d["dtb"])

    print(f"# Generated by builder/import-dtbloader-boards.py from dtbloader {commit}")
    print("# (https://github.com/TravMurav/dtbloader, BSD-3-Clause). Do not hand-edit generated rows;")
    print("# add local rows at the bottom, below the marker. Columns are TAB-separated:")
    print("#   vendor  product_re  dtb  name  auto  verified  source")
    print("# vendor = SMBIOS type 1 Manufacturer (exact). product_re = ERE on type 1 Product Name.")
    print("# auto=yes: GRUB boots it without asking. verified=yes: someone booted this ISO on it.")
    for (v, p, dtb), d in sorted(rows.items(), key=lambda kv: (kv[0][2], kv[0][0], kv[0][1])):
        # Never auto-boot a vendor/product that an .extra_match device also claims: GRUB would
        # silently boot the plain variant (e.g. T14s IPS) on the other one (T14s OLED). Those
        # machines get the menu instead, where both DTBs are listed.
        auto = "yes" if not d["extra_match"] and (v, p) not in ambiguous and plain.get((v, p)) == {dtb} else "no"
        verified = "yes" if (v, p, dtb) == ("LENOVO", "^83ED", "x1e80100-lenovo-yoga-slim7x.dtb") else "no"
        src = d["src"] + (" (tentative)" if d["tentative"] else "")
        print("\t".join([v, p, dtb, d["name"], auto, verified, src]))
    print("# --- local rows below ---")


if __name__ == "__main__":
    main()
