#!/bin/bash
# Stage every Snapdragon X1/X2 device tree from the linux-aarch64 package into the GRUB
# profile dir, and generate the two GRUB snippets grub.cfg/loopback.cfg source:
#
#   boards-match.cfg  compares SMBIOS type 1 vendor/product (read by grub.cfg) against
#                     configs/boards.tsv and sets board_dtb/board_name on an auto=yes match.
#   boards-menu.cfg   one "Swarmarchy on <laptop>" entry per DTB, for machines no row matched
#                     (or to override a wrong match). Rows' names are used where known.
#
# The board boots via device tree, not ACPI, and the DTB must be handed over before Linux
# starts -- so the choice can only be made here, in GRUB. Each entry also passes
# swarmarchy.devicetree=dtbs/qcom/<file> on the kernel cmdline so the installer
# (swarmarchy-hw-snapdragon dtb) knows which DTB the live system booted with.
#
# mkarchiso copies non-.cfg files in grub/ verbatim and runs its %INSTALL_DIR%/%ARCH%
# substitutions over every grub/*.cfg, so the generated entries may use those placeholders.
#
# Every entry also carries the board kernel arguments (efi=novamap, pd_ignore_unused, ...) from
# the layer's swarmarchy-hw-snapdragon -- the single list the installed system's limine.conf also
# uses. The live system needs them as much as the installed one does.
#
# Usage: generate-grub-boards.sh LINUX_PKG BOARDS_TSV GRUB_DIR SNAPDRAGON_HW

set -euo pipefail

linux_pkg="$1"
boards_tsv="$2"
grub_dir="$3"
snapdragon_hw="$4"

board_args="$(bash "$snapdragon_hw" cmdline --all)"
if [[ -z $board_args || $board_args == *[\"\$\\]* ]]; then
  echo "ERROR: no usable board kernel arguments from $snapdragon_hw cmdline --all" >&2
  exit 1
fi

dtb_re='^boot/dtbs/qcom/(x1e|x1p|hamoa|purwa|glymur|mahua)[^/]*\.dtb$'

mapfile -t dtbs < <(bsdtar -tf "$linux_pkg" | grep -E "$dtb_re" | grep -v -- '-el2\.dtb$' | sort)
if (( ${#dtbs[@]} == 0 )); then
  echo "ERROR: no Snapdragon X device trees found in $linux_pkg" >&2
  exit 1
fi

mkdir -p "$grub_dir"
bsdtar -xf "$linux_pkg" -C "$grub_dir" --strip-components 3 "${dtbs[@]}"

declare -A have name_of
for d in "${dtbs[@]}"; do
  f="${d##*/}"
  [[ -s $grub_dir/$f ]] || { echo "ERROR: extracted $f is empty" >&2; exit 1; }
  have[$f]=1
done

match="$grub_dir/boards-match.cfg"
menu="$grub_dir/boards-menu.cfg"

{
  echo "# Generated by builder/generate-grub-boards.sh from configs/boards.tsv -- do not edit."
  echo "# Expects smb_vendor/smb_product from grub.cfg; sets board_dtb/board_name on a match."
  echo "# swarm_board_args: the board kernel arguments, for grub.cfg/loopback.cfg's matched entries."
  printf 'set swarm_board_args="%s"\n' "$board_args"
} >"$match"

matched=0 dropped=0
while IFS=$'\t' read -r vendor product_re dtb bname auto verified _; do
  [[ -z $vendor || $vendor == \#* ]] && continue
  if [[ -z ${have[$dtb]:-} ]]; then
    echo "WARNING: boards.tsv row for '$bname' names $dtb, which linux-aarch64 does not ship; skipped" >&2
    dropped=$(( dropped + 1 ))
    continue
  fi
  [[ -z ${name_of[$dtb]:-} ]] && name_of[$dtb]="$bname"
  [[ $auto == "yes" ]] || continue
  # First match wins; rows are unique per vendor/product_re for auto=yes (see the importer).
  # Nested ifs, not `&&`: GRUB's script language documents no && / || operators.
  printf 'if [ -z "${board_dtb}" -a "${smb_vendor}" = "%s" ]; then\n' "$vendor"
  printf '    if regexp '"'"'%s'"'"' "${smb_product}"; then\n' "$product_re"
  printf '        set board_dtb="%s"\n        set board_name="%s"\n    fi\nfi\n' "$dtb" "$bname"
  matched=$(( matched + 1 ))
done <"$boards_tsv" >>"$match"

{
  echo "# Generated by builder/generate-grub-boards.sh -- do not edit."
  echo "# Uses swarm_linux_args, set by grub.cfg / loopback.cfg for their boot medium."
  for d in "${dtbs[@]}"; do
    f="${d##*/}"
    label="${name_of[$f]:-${f%.dtb}}"
    cat <<EOF
menuentry "Swarmarchy on ${label} (${f%.dtb})" --class arch --class gnu-linux --class gnu --class os {
    set gfxpayload=keep
    linux /%INSTALL_DIR%/boot/%ARCH%/vmlinuz-linux \${swarm_linux_args} ${board_args} swarmarchy.devicetree=dtbs/qcom/${f}
    initrd /%INSTALL_DIR%/boot/%ARCH%/initramfs-linux.img
    devicetree /boot/grub/${f}
}
EOF
  done
} >"$menu"

echo "GRUB boards: ${#dtbs[@]} device trees staged, $matched SMBIOS rows, $dropped rows skipped"
